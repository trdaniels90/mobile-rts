"""Soviet Tesla Coil, modelled in Blender and voxelized for the game.
python3 -I tools/blender/tesla.py <out_dir>  ->  tesla.js (STRUCTURES.tesla body for models.js), tesla.preview.js, tesla.blend
Box: x -2..26, y -2..50, z 0..58. The coil stands at (12, 35); its tip is at z 50 (art.js and world.js aim effects there).
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from voxlib import Scene, greedy_boxes, emit

CX, CY = 12.0, 35.0
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

s = Scene()
s.tube((CX, CY, 0.0), (CX, CY, 1.2), 10.5, '#0f0e0b', 'rough', name='pit', verts=40)               # dark round base
s.torus((CX, CY, 1.4), 9.7, 0.75, 'main', 'metal', name='team_ring')                                # the side's colour round the base
s.tube((CX, CY, 1.0), (CX, CY, 3.5), 3.6, '#2a2926', 'metal', name='foot', verts=16)
s.tube((CX, CY, 3.0), (CX, CY, 11.0), 2.1, '#3a3b3e', 'metal', name='stem', verts=12)          # the cone stands up off the ground on a short stem
s.tube((CX, CY, 3.0), (CX, CY, 49.0), 1.5, '#2c2e30', 'metal', name='core', verts=12)
RINGS = 7
for i in range(RINGS):                                                                              # a cone of thin white rings
    z = 12.0 + i * 5.6
    r = 7.6 - (7.6 - 2.6) * i / (RINGS - 1)
    s.torus((CX, CY, z), r, 0.85, '#eceef0', 'metal', name='ring')
s.sphere((CX, CY, 50.0), (3.1, 3.1, 3.1), '#a7b5d6', 'metal', name='ball')                          # blue-silver ball, tip at z 50
boxes = greedy_boxes(s.voxelize(-2, -2, 26, 50, 58))
s.save_blend(os.path.join(out, 'tesla.blend'))

body = '\n'.join('    ' + l for l in emit(boxes).split('\n'))
open(os.path.join(out, 'tesla.js'), 'w').write(
    "// Generated by tools/blender/tesla.py (Blender model, voxelized)\n"
    "  tesla(pal) {\n    const m = new VModel(-2, -2, 26, 50, 58);\n    slabV(m, 0, 22, 24, 48);\n" + body + "\n    return m;\n  },\n")
open(os.path.join(out, 'tesla.preview.js'), 'w').write(
    "STRUCTURES_SHARED.tesla = function (pal) {\n  const m = new VModel(-2, -2, 26, 50, 58);\n  slabV(m, 0, 22, 24, 48);\n" + emit(boxes) + "\n  return m;\n};\n")
print('boxes', len(boxes))
