"""Allied AA Gun, modelled in Blender and voxelized for the game.
python3 -I tools/blender/aagun.py <out_dir>   ->  aagun.js (builders to paste in models.js), aagun.blend"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from voxlib import Scene, greedy_boxes, emit

GUN, STEEL, METAL, OLIVE, SAND, SAND2, CONC, BIB = '#34362f', '#9ba1a3', '#7b7e78', '#5a6238', '#ad9466', '#8a744c', '#8f8d84', '#6e6352'
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

# ---------------------------------------------------------------- head: the swivelling twin gun
# Origin is the swivel, barrels point along +x. Box: x -6..12, y -6..6, z 0..12.
h = Scene()
PIV = (0, 0, 4.8)
ELEV = math.radians(30)
dirv = (math.cos(ELEV), 0, math.sin(ELEV))
def along(t, y=0):          # a point t voxels along the barrels from the trunnion
    return (PIV[0] + dirv[0] * t, y, PIV[2] + dirv[2] * t)

h.tube((0, 0, 0), (0, 0, 2.4), 3.4, GUN, 'metal', name='pedestal')
h.tube((0, 0, 1.6), (0, 0, 2.8), 4.4, METAL, 'metal', name='turntable')
h.cube((0, 0, 4.4), (8.0, 6.8, 3.4), 'main', 'metal', name='cradle')              # gun body
h.sphere((2.6, 0, 4.6), (2.6, 3.4, 1.9), 'main', 'metal', name='cradle_nose')
for s in (-1, 1):
    y = 2.2 * s
    h.tube(along(-3, y), along(10.8, y), 0.95, GUN, 'metal', name='barrel')
    h.tube(along(0.5, y), along(4.6, y), 1.45, STEEL, 'metal', name='recoil_sleeve')
    h.tube(along(8.8, y), along(10.9, y), 1.35, '#25261f', 'metal', name='muzzle_brake')
h.cube((-4.2, 0, 4.6), (3.4, 5.0, 2.8), 'dark', 'metal', name='counterweight')
for s in (-1, 1):
    h.cube((-1.2, 4.6 * s, 3.4), (4.4, 2.0, 2.2), OLIVE, 'matte', name='ammo_box')
    h.cube((-1.2, 4.6 * s, 4.6), (4.4, 2.0, 0.4), '#464b2b', 'matte', name='ammo_lid')
h.cube((-1.0, 0, 6.6), (2.6, 2.0, 1.2), '#35505f', 'glass', name='sight')

hb = greedy_boxes(h.voxelize(-6, -6, 12, 6, 12))
h.save_blend(os.path.join(out, 'aagun_head.blend'))

# ---------------------------------------------------------------- base: pad, sandbag ring, crates
# Origin is the cell's top-left; the cell is 24 x 24 and the gun sits at (12, 12). Box: -2..26, z 0..6.
s = Scene()
s.cube((12, 12, 0.5), (24, 24, 1), BIB, 'rough', name='bib')
s.tube((12, 12, 0), (12, 12, 1.2), 8.4, CONC, 'rough', name='concrete_pad', verts=32)
R, N = 10.2, 19
for layer in (0, 1):
    for i in range(N):
        a = (i + layer * 0.5) / N * 2 * math.pi
        if layer == 1 and math.sin(a) > 0.55:      # keep the south side low so the gun shows
            continue
        x, y = 12 + R * math.cos(a), 12 + R * math.sin(a)
        s.sphere((x, y, 1.9 + layer * 1.8), (1.85, 1.3, 1.1), SAND if (i + layer) % 2 else SAND2, 'rough',
                 rot=(0, 0, math.degrees(a) + 90), name='sandbag')
for cx, cy in ((3.6, 3.6), (20.4, 3.6), (3.6, 20.4)):
    s.cube((cx, cy, 2.2), (4.4, 3.2, 2.4), OLIVE, 'matte', rot=(0, 0, 45 if cx > 12 else -20), name='crate')
    s.cube((cx, cy, 3.5), (4.4, 3.2, 0.3), '#464b2b', 'matte', rot=(0, 0, 45 if cx > 12 else -20), name='crate_lid')
sb = greedy_boxes(s.voxelize(-2, -2, 26, 26, 7))
s.save_blend(os.path.join(out, 'aagun_base.blend'))

with open(os.path.join(out, 'aagun.js'), 'w') as f:
    f.write("// Generated by tools/blender/aagun.py (Blender model, voxelized)\n")
    f.write("// ---- STRUCTURES.aagun\n  aagun(pal) {\n    const m = new VModel(-2, -2, 26, 26, 7);\n")
    f.write('\n'.join('    ' + l for l in emit(sb).split('\n')) + "\n    return m;\n  },\n")
    f.write("// ---- HEADS.aagun\n  aagun: [(pal) => {\n    const m = new VModel(-6, -6, 12, 6, 12);\n")
    f.write('\n'.join('    ' + l for l in emit(hb).split('\n')) + "\n    return m;\n  }, 12, 12, 1],\n")
with open(os.path.join(out, 'aagun.preview.js'), 'w') as f:   # for preview-aagun.js: swaps the models in at run time
    f.write("STRUCTURES.aagun = function (pal) {\n    const m = new VModel(-2, -2, 26, 26, 7);\n" + emit(sb) + "\n    return m;\n};\n")
    f.write("HEADS.aagun = [function (pal) {\n    const m = new VModel(-6, -6, 12, 6, 12);\n" + emit(hb) + "\n    return m;\n}, 12, 12, 1];\n")
print('head boxes', len(hb), 'base boxes', len(sb))
