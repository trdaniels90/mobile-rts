"""Soviet Flame Tower, modelled in Blender and voxelized for the game.
python3 -I tools/blender/ftur.py <out_dir>  ->  ftur.js (STRUCTURES.ftur body for models.js), ftur.preview.js, ftur.blend
Box: x -2..26, y -2..26, z 0..30. The tower stands at (12, 13); its fire bowl is at z 25 (art.js and world.js aim effects there).
Design taken from an AI-generated reference: a six-sided tower with an arched stone foot, a braced frame, a brick
room in the team colour, an open lattice and a railed platform carrying a burning bowl.
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from voxlib import Scene, greedy_boxes, emit

CX, CY = 12.0, 13.0
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

STONE, STONE2, TIMBER, TIMBER2, BRACE, IRON = '#8a7d70', '#a4978a', '#4a3828', '#6e5539', '#8a6d48', '#2a2b2d'
BRICK, EMBER, FIRE, FIREHI, BIB = '#96503a', '#ff7a1a', '#ff9a2a', '#ffd25a', '#5f574c'


def hexagon(r, turn=0.0):
    return [(CX + r * math.cos(math.radians(turn + 60 * k)), CY + r * math.sin(math.radians(turn + 60 * k))) for k in range(6)]


def corner(r, k, turn=0.0):
    a = math.radians(turn + 60 * k)
    return CX + r * math.cos(a), CY + r * math.sin(a)


s = Scene()
s.cube((12, 12, 0.5), (24, 24, 1.0), BIB, 'rough', name='pad')
# ---- arched stone foot: a six-sided stump, wide at the ground
s.prism(hexagon(9.4), hexagon(7.2), 1.0, 7.0, STONE, 'rough', name='foot')
s.prism(hexagon(7.6), hexagon(7.6), 7.0, 8.0, STONE2, 'rough', name='foot_cap')
for k in range(6):                                                               # an arch in every face, fire glowing inside
    a = math.radians(30 + 60 * k)
    s.cube((CX + 7.6 * math.cos(a), CY + 7.6 * math.sin(a), 3.2), (2.4, 4.0, 4.4), '#1a120d', 'matte', rot=(0, 0, 30 + 60 * k), name='arch')
    s.cube((CX + 7.9 * math.cos(a), CY + 7.9 * math.sin(a), 2.5), (2.0, 2.0, 3.0), EMBER, 'glow', rot=(0, 0, 30 + 60 * k), name='arch_glow')
# ---- braced frame: brick panels between timber corner posts, narrowing
s.prism(hexagon(6.4), hexagon(5.4), 8.0, 13.0, BRICK, 'rough', name='frame_infill')
for k in range(6):
    x0, y0 = corner(6.7, k)
    x1, y1 = corner(5.7, k)
    s.tube((x0, y0, 7.6), (x1, y1, 13.2), 0.75, TIMBER2, 'rough', name='frame_post', verts=8)
    xa, ya = corner(6.3, k)
    xb, yb = corner(5.6, k + 1)
    s.tube((xa, ya, 8.4), (xb, yb, 12.6), 0.5, BRACE, 'rough', name='frame_brace', verts=8)   # diagonal brace across each panel
s.prism(hexagon(6.3), hexagon(6.3), 13.0, 14.0, TIMBER, 'rough', name='floor_low')            # floor under the room
# ---- brick room in the team colour
s.prism(hexagon(5.4), hexagon(5.2), 14.0, 20.0, 'main', 'metal', name='room')
s.prism(hexagon(5.5), hexagon(5.5), 18.6, 20.0, 'light', 'metal', name='room_band')
for k in range(6):
    a = math.radians(30 + 60 * k)
    s.cube((CX + 4.5 * math.cos(a), CY + 4.5 * math.sin(a), 16.5), (1.4, 1.6, 1.8), '#14100d', 'matte', rot=(0, 0, 30 + 60 * k), name='window')
    x0, y0 = corner(5.5, k)
    s.tube((x0, y0, 14.0), (x0, y0, 20.0), 0.6, 'dark', 'metal', name='room_corner', verts=8)
s.prism(hexagon(6.1), hexagon(6.1), 20.0, 21.0, TIMBER, 'rough', name='floor_high')           # floor over the room
# ---- open lattice with the fuel pipe up the middle
s.tube((CX, CY, 20.5), (CX, CY, 25.0), 1.6, IRON, 'metal', name='fuel_pipe', verts=12)
for k in range(6):
    x0, y0 = corner(5.2, k)
    x1, y1 = corner(5.6, k)
    s.tube((x0, y0, 20.5), (x1, y1, 24.2), 0.6, TIMBER2, 'rough', name='lattice_post', verts=8)
# ---- railed platform and the fire bowl
s.prism(hexagon(6.6), hexagon(6.6), 24.0, 25.0, TIMBER2, 'rough', name='platform')
for k in range(6):
    x0, y0 = corner(6.4, k)
    x1, y1 = corner(6.4, k + 1)
    s.tube((x0, y0, 25.6), (x1, y1, 25.6), 0.55, TIMBER, 'rough', name='rail', verts=8)
    s.tube((x0, y0, 24.6), (x0, y0, 26.2), 0.6, TIMBER, 'rough', name='rail_post', verts=8)
s.tube((CX, CY, 24.6), (CX, CY, 26.0), 4.0, IRON, 'metal', name='bowl', verts=16)
s.tube((CX, CY, 25.0), (CX, CY, 26.4), 3.1, EMBER, 'glow', name='bowl_fire', verts=16)
s.sphere((CX, CY, 26.6), (2.4, 2.4, 2.0), FIRE, 'glow', name='flame')
s.sphere((CX - 0.3, CY, 27.4), (1.4, 1.4, 2.0), FIREHI, 'glow', name='flame_tip')
# ---- fuel drums and a crate at the foot
for (x, y) in ((2.8, 20.6), (5.4, 22.0)):
    s.tube((x, y, 1.0), (x, y, 4.4), 1.5, 'light', 'metal', name='drum', verts=12)
    s.tube((x, y, 2.4), (x, y, 3.0), 1.65, 'dark', 'metal', name='drum_band', verts=12)
s.cube((20.6, 21.0, 2.2), (3.6, 2.6, 2.4), '#8a8478', 'metal', name='crate')
s.cube((20.6, 21.0, 3.5), (3.8, 2.8, 0.5), '#a59f92', 'metal', name='crate_lid')
boxes = greedy_boxes(s.voxelize(-2, -2, 26, 26, 30))
s.save_blend(os.path.join(out, 'ftur.blend'))

body = '\n'.join('    ' + l for l in emit(boxes).split('\n'))
open(os.path.join(out, 'ftur.js'), 'w').write(
    "// Generated by tools/blender/ftur.py (Blender model, voxelized)\n"
    "  ftur(pal) {\n    const m = new VModel(-2, -2, 26, 26, 30);\n" + body + "\n    return m;\n  },\n")
open(os.path.join(out, 'ftur.preview.js'), 'w').write(
    "STRUCTURES_SHARED.ftur = function (pal) {\n  const m = new VModel(-2, -2, 26, 26, 30);\n" + emit(boxes) + "\n  return m;\n};\n")
print('boxes', len(boxes))
